package Latihan_Praktikum;

public class AlatTulis {
    String merk;
    String warna;

    public void digunakan() {
        System.out.println("Alat Tulis sedang digunakan");
    }

    public void disimpan() {
        System.out.println("Alat Tulis sedang disimpan");
    }

    public void cetakInfo() {
        System.out.println("Merk : " + merk);
        System.out.println("Warna : " + warna);
    }
}
